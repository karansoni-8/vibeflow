import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { useAuthStore } from '../../stores/authStore';
import { LogoFull } from '../ui/Logo';
import { sampleProjects } from '../../data/sampleProjects';
import { createProject, getProjects } from '../../lib/api';
import { LayoutDashboard, FolderKanban, Component, Settings, LogOut, Plus, Clock, Sparkles } from 'lucide-react';
import { motion } from 'framer-motion';
import { cn } from '../../lib/cn';

export const Dashboard: React.FC = () => {
  const { user, signOut } = useAuthStore();
  const navigate = useNavigate();
  const [projects, setProjects] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [newProjectName, setNewProjectName] = useState('');
  const [newProjectLang, setNewProjectLang] = useState('javascript');
  const [vibePrompt, setVibePrompt] = useState('');

  useEffect(() => {
    fetchProjects();
  }, []);

  const fetchProjects = async () => {
    setLoading(true);
    const { data } = await getProjects();
    if (data) setProjects(data);
    setLoading(false);
  };

  const handleCreateProject = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newProjectName.trim()) return;
    const { data } = await createProject(newProjectName, newProjectLang);
    if (data) {
      navigate(`/ide/${data.id}`);
    }
    setIsModalOpen(false);
  };

  const handleUseTemplate = async (template: any) => {
    const { data } = await createProject(template.name, template.language);
    if (data) {
      // NOTE: File creation should be handled or IDE will create default
      navigate(`/ide/${data.id}`);
    }
  };

  const handleVibeCreate = () => {
    if (!vibePrompt.trim()) return;
    // For now, open modal with preset name, ideally we'd pass vibePrompt to IDE
    setNewProjectName('Generated by AI');
    setIsModalOpen(true);
  };

  const getTimeOfDay = () => {
    const hour = new Date().getHours();
    if (hour < 12) return 'morning';
    if (hour < 18) return 'afternoon';
    return 'evening';
  };

  return (
    <div className="flex h-screen bg-[#06090e] text-white font-sans overflow-hidden">
      {/* Sidebar */}
      <aside className="w-64 border-r border-white/10 bg-[#0b0f17] flex flex-col justify-between p-6">
        <div>
          <div className="mb-10 pl-2">
            <LogoFull size={32} />
          </div>
          <nav className="flex flex-col gap-2">
            {[
              { icon: <LayoutDashboard size={20} />, label: 'Dashboard', active: true },
              { icon: <FolderKanban size={20} />, label: 'Projects' },
              { icon: <Component size={20} />, label: 'Templates' },
              { icon: <Settings size={20} />, label: 'Settings' },
            ].map((item, i) => (
              <button 
                key={i} 
                className={cn(
                  "flex items-center gap-3 px-4 py-3 rounded-xl transition-all",
                  item.active ? "bg-cyan-500/10 text-cyan-400 font-medium" : "text-gray-400 hover:text-white hover:bg-white/5"
                )}
              >
                {item.icon}
                {item.label}
              </button>
            ))}
          </nav>
        </div>
        <div className="mt-auto">
          <div className="flex items-center gap-3 px-4 py-3 rounded-xl bg-white/5 mb-4">
            <div className="w-8 h-8 rounded-full bg-gradient-to-tr from-cyan-500 to-purple-500 flex items-center justify-center text-sm font-bold">
              {user?.displayName?.[0]?.toUpperCase() || 'U'}
            </div>
            <div className="flex-1 truncate">
              <p className="text-sm font-medium truncate">{user?.displayName || 'User'}</p>
            </div>
          </div>
          <button 
            onClick={() => signOut()}
            className="flex items-center gap-3 px-4 py-3 w-full rounded-xl text-gray-400 hover:text-red-400 hover:bg-red-400/10 transition-all"
          >
            <LogOut size={20} />
            Logout
          </button>
        </div>
      </aside>

      {/* Main Content */}
      <main className="flex-1 overflow-y-auto p-10 bg-[#06090e]">
        <div className="max-w-6xl mx-auto space-y-12">
          
          <header>
            <h1 className="text-3xl font-bold mb-2">Good {getTimeOfDay()}, {user?.displayName?.split(' ')[0] || 'Developer'} 👋</h1>
            <p className="text-gray-400">Ready to build something awesome?</p>
          </header>

          {/* Vibe Mode Input */}
          <section className="bg-[#0b0f17] border border-white/10 rounded-2xl p-6 relative overflow-hidden">
            <div className="absolute top-0 right-0 w-64 h-64 bg-cyan-500/10 rounded-full blur-[80px]" />
            <h2 className="text-lg font-semibold flex items-center gap-2 mb-4">
              <Sparkles size={20} className="text-cyan-400" /> Vibe Mode
            </h2>
            <div className="relative">
              <textarea 
                value={vibePrompt}
                onChange={(e) => setVibePrompt(e.target.value)}
                placeholder="What do you want to build? e.g. 'A simple express server that connects to sqlite'"
                className="w-full bg-[#141c2b] border border-white/10 rounded-xl p-4 min-h-[100px] text-white placeholder:text-gray-500 focus:outline-none focus:border-cyan-500/50 resize-none"
              />
              <button 
                onClick={handleVibeCreate}
                className="absolute bottom-4 right-4 bg-white text-black px-4 py-2 rounded-lg font-medium hover:bg-gray-200 transition-colors flex items-center gap-2"
              >
                Create with AI
              </button>
            </div>
          </section>

          {/* Recent Projects */}
          <section>
            <div className="flex items-center justify-between mb-6">
              <h2 className="text-xl font-semibold">Recent Projects</h2>
            </div>
            
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
              <button 
                onClick={() => setIsModalOpen(true)}
                className="h-40 rounded-2xl border border-dashed border-white/20 hover:border-cyan-400/50 hover:bg-cyan-400/5 flex flex-col items-center justify-center gap-3 transition-all group"
              >
                <div className="w-12 h-12 rounded-full bg-white/5 flex items-center justify-center group-hover:scale-110 transition-transform">
                  <Plus size={24} className="text-gray-400 group-hover:text-cyan-400" />
                </div>
                <span className="font-medium text-gray-400 group-hover:text-cyan-400">New Project</span>
              </button>

              {!loading && projects.length === 0 && (
                <div className="col-span-1 md:col-span-2 flex items-center justify-center h-40 rounded-2xl border border-white/5 bg-[#0b0f17]">
                  <p className="text-gray-500">No projects yet. Turn your first idea into code.</p>
                </div>
              )}

              {projects.map((project) => (
                <div 
                  key={project.id}
                  onClick={() => navigate(`/ide/${project.id}`)}
                  className="h-40 rounded-2xl bg-[#0b0f17] border border-white/10 p-5 hover:border-white/30 cursor-pointer transition-all flex flex-col group relative overflow-hidden"
                >
                  <div className="absolute top-0 left-0 w-full h-1 bg-gradient-to-r from-cyan-500 to-purple-500 opacity-0 group-hover:opacity-100 transition-opacity" />
                  <div className="flex justify-between items-start mb-auto">
                    <h3 className="font-semibold text-lg truncate pr-4">{project.name}</h3>
                    <span className="text-xs px-2 py-1 rounded-md bg-white/5 text-gray-300 border border-white/10 uppercase">
                      {project.language}
                    </span>
                  </div>
                  <div className="flex items-center text-xs text-gray-500 gap-2">
                    <Clock size={14} />
                    Modified recently
                  </div>
                </div>
              ))}
            </div>
          </section>

          {/* Templates */}
          <section>
            <h2 className="text-xl font-semibold mb-6">Get Started with Templates</h2>
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
              {sampleProjects.map((template, idx) => (
                <div key={idx} className="bg-[#0b0f17] border border-white/10 rounded-xl p-5 hover:border-white/20 transition-all flex flex-col h-48">
                  <div className="flex justify-between items-start mb-2">
                    <h3 className="font-medium truncate">{template.name}</h3>
                    <span className="text-[10px] px-1.5 py-0.5 rounded bg-white/5 text-gray-400 uppercase">{template.language}</span>
                  </div>
                  <p className="text-xs text-gray-500 line-clamp-2 mb-auto">{template.description}</p>
                  <button 
                    onClick={() => handleUseTemplate(template)}
                    className="w-full py-2 bg-white/5 hover:bg-white/10 border border-white/10 rounded-lg text-sm font-medium transition-colors mt-4"
                  >
                    Use Template
                  </button>
                </div>
              ))}
            </div>
          </section>
        </div>
      </main>

      {/* Create Modal */}
      {isModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm">
          <motion.div 
            initial={{ opacity: 0, scale: 0.95 }}
            animate={{ opacity: 1, scale: 1 }}
            className="bg-[#0b0f17] border border-white/10 rounded-2xl p-6 w-full max-w-md shadow-2xl"
          >
            <h2 className="text-xl font-bold mb-4">Create New Project</h2>
            <form onSubmit={handleCreateProject}>
              <div className="space-y-4 mb-6">
                <div>
                  <label className="block text-sm font-medium text-gray-400 mb-1">Project Name</label>
                  <input 
                    type="text" 
                    value={newProjectName}
                    onChange={(e) => setNewProjectName(e.target.value)}
                    required
                    autoFocus
                    className="w-full bg-[#141c2b] border border-white/10 rounded-lg px-4 py-2 text-white focus:outline-none focus:border-cyan-500"
                  />
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-400 mb-1">Language</label>
                  <select 
                    value={newProjectLang}
                    onChange={(e) => setNewProjectLang(e.target.value)}
                    className="w-full bg-[#141c2b] border border-white/10 rounded-lg px-4 py-2 text-white focus:outline-none focus:border-cyan-500"
                  >
                    <option value="javascript">JavaScript</option>
                    <option value="typescript">TypeScript</option>
                    <option value="python">Python</option>
                    <option value="cpp">C++</option>
                    <option value="java">Java</option>
                  </select>
                </div>
              </div>
              <div className="flex justify-end gap-3">
                <button 
                  type="button" 
                  onClick={() => setIsModalOpen(false)}
                  className="px-4 py-2 text-gray-400 hover:text-white"
                >
                  Cancel
                </button>
                <button 
                  type="submit"
                  className="px-4 py-2 bg-white text-black rounded-lg font-medium hover:bg-gray-200 transition-colors"
                >
                  Create Project
                </button>
              </div>
            </form>
          </motion.div>
        </div>
      )}
    </div>
  );
};
